const months = ['Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec', 'Jan']

function spark(base: number, drift: number): { month: string; value: number }[] {
  return months.map((month, i) => ({
    month,
    value: +(base + drift * i + Math.sin(i * 1.2) * 1.5).toFixed(1),
  }))
}

